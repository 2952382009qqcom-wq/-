# ===== 字体路径 =====
FONT_TITLE = "C:/Windows/Fonts/simhei.ttf"
FONT_BODY = "C:/Windows/Fonts/simsun.ttc"
FONT_KAI = "C:/Windows/Fonts/simkai.ttf"
FONT_FANG = "C:/Windows/Fonts/simfang.ttf"

# ===== 配色 =====
CLR_PRIMARY = (13, 27, 42)
CLR_SECONDARY = (27, 42, 74)
CLR_ACCENT = (65, 90, 119)
CLR_BODY = (51, 51, 51)
CLR_LIGHT = (119, 119, 119)
CLR_DIV = (200, 200, 200)
CLR_WHITE = (255, 255, 255)
CLR_BG_STRIPE = (245, 247, 250)

INDENT = '        '  # 约两个全角字符


def tight_text(text):
    """收紧中英文/数字之间不必要的空格，减少 PDF 中不该出现的断行。"""
    replacements = {
        'AI 法律': 'AI法律',
        'AI + 法律': 'AI+法律',
        'AI 法条': 'AI法条',
        'AI 输出': 'AI输出',
        'AI 生成': 'AI生成',
        'AI 助手': 'AI助手',
        'AI 产品': 'AI产品',
        'AI 辅助': 'AI辅助',
        'AI 平台': 'AI平台',
        'AI 能力': 'AI能力',
        'AI 写': 'AI写',
        'BM25 + ': 'BM25+',
        '5 大': '5大',
        '6 种': '6种',
        '3 个月': '3个月',
        '6-12 个月': '6-12个月',
        '1-3 年': '1-3年',
        '1-2 秒': '1-2秒',
        '30-60 秒': '30-60秒',
        '500+ 法律': '500+法律',
        '349 条': '349条',
        '42 部': '42部',
        '83 万': '83万',
        '6.7 万': '6.7万',
        '1.5 万': '1.5万',
        '1.2 万': '1.2万',
        '4000 多万': '4000多万',
        '1.7 亿': '1.7亿',
        '59 万': '59万',
        '60 多万': '60多万',
        '2026 年': '2026年',
        '2027 年': '2027年',
        '2030 年': '2030年',
        '2035 年': '2035年',
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    text = re.sub(r'(\d)\s+([年月日个万亿条部件人家元秒%])', r'\1\2', text)
    text = re.sub(r'([A-Za-z]+)\s+([\u4e00-\u9fff])', r'\1\2', text)
    return text


class ChinesePDF(FPDF):
    def __init__(self):
        super().__init__('P', 'mm', 'A4')
        self.set_auto_page_break(True, 25)
        self.set_margins(25, 25, 25)
        self.add_font('T', '', FONT_TITLE)
        self.add_font('B', '', FONT_BODY)
        self.add_font('K', '', FONT_KAI)
        self.add_font('F', '', FONT_FANG)
        self.cw = self.w - self.l_margin - self.r_margin
        self.toc_entries = []

    def header(self):
        if self.page_no() == 1:
            return
        self.set_font('B', '', 8)
        self.set_text_color(*CLR_LIGHT)
        self.cell(self.cw, 6, '明鉴 AI法律文书智能助手 - 商业计划书', align='R')
        self.ln(2)
        self.set_draw_color(*CLR_DIV)
        self.set_line_width(0.3)
        x0 = self.l_margin
        y0 = self.get_y()
        self.line(x0, y0, x0 + self.cw, y0)
        self.ln(4)

    def footer(self):
        if self.page_no() == 1:
            return
        self.set_y(-20)
        y0 = self.get_y()
        self.set_draw_color(*CLR_DIV)
        self.set_line_width(0.3)
        x0 = self.l_margin
        self.line(x0, y0, x0 + self.cw, y0)
        self.ln(3)
        self.set_font('B', '', 8)
        self.set_text_color(*CLR_LIGHT)
        self.cell(self.cw, 5, '- %s -' % self.page_no(), align='C')

    # ===== Layout helpers =====
    def cover_title(self, text, size=32):
        self.ln(30)
        self.set_font('T', '', size)
        self.set_text_color(*CLR_PRIMARY)
        self.cell(self.cw, 16, text, align='C', new_x='LMARGIN', new_y='NEXT')
        self.ln(4)

    def cover_line(self, text, size=11):
        self.set_font('F', '', size)
        self.set_text_color(*CLR_BODY)
        self.cell(self.cw, 8, text, align='C', new_x='LMARGIN', new_y='NEXT')

    def h1(self, text):
        self.ln(4)
        self.set_font('T', '', 18)
        self.set_text_color(*CLR_PRIMARY)
        self.cell(self.cw, 10, text, align='L', new_x='LMARGIN', new_y='NEXT')
        y0 = self.get_y()
        self.set_draw_color(*CLR_PRIMARY)
        self.set_line_width(0.6)
        self.line(self.l_margin, y0 + 1, self.l_margin + 60, y0 + 1)
        self.ln(6)

    def h2(self, text):
        self.ln(2)
        self.set_font('T', '', 14)
        self.set_text_color(*CLR_SECONDARY)
        self.cell(self.cw, 8, text, align='L', new_x='LMARGIN', new_y='NEXT')
        self.ln(3)

    def h3(self, text):
        self.ln(1)
        self.set_font('T', '', 12)
        self.set_text_color(*CLR_ACCENT)
        self.cell(self.cw, 7, text, align='L', new_x='LMARGIN', new_y='NEXT')
        self.ln(2)

    def body(self, text):
        self.set_font('B', '', 11)
        self.set_text_color(*CLR_BODY)
        text = tight_text(text)
        self.multi_cell(self.cw, 7.5, INDENT + text, align='L')
        self.ln(1)

    def body_ni(self, text):
        self.set_font('B', '', 11)
        self.set_text_color(*CLR_BODY)
        text = tight_text(text)
        self.multi_cell(self.cw, 7.5, text, align='L')
        self.ln(1)

    def bullet(self, text, level=0):
        indent = level * 8
        prefix = {0: '●', 1: '○', 2: '▪'}.get(level, '▪')
        self.set_font('B', '', 11)
        self.set_text_color(*CLR_BODY)
        text = tight_text(text)
        x0 = self.l_margin + indent
        self.set_x(x0)
        self.cell(6, 7, prefix, align='C')
        self.multi_cell(self.cw - indent - 6, 7, text, align='L')
        self.ln(0.5)

    def numbered(self, num, text):
        self.set_font('B', '', 11)
        self.set_text_color(*CLR_BODY)
        text = tight_text(text)
        self.cell(8, 7, '%s.' % num, align='L')
        self.multi_cell(self.cw - 8, 7, text, align='L')
        self.ln(0.5)

    def table(self, headers, rows, col_widths=None):
        if col_widths is None:
            col_widths = [self.cw / len(headers)] * len(headers)
        self.set_fill_color(*CLR_PRIMARY)
        self.set_text_color(*CLR_WHITE)
        self.set_font('T', '', 10)
        for h, w in zip(headers, col_widths):
            self.cell(w, 9, tight_text(h), border=0, fill=True, align='C')
        self.ln()
        self.set_text_color(*CLR_BODY)
        self.set_font('B', '', 9)
        for ri, row in enumerate(rows):
            if ri % 2 == 0:
                self.set_fill_color(*CLR_BG_STRIPE)
            else:
                self.set_fill_color(*CLR_WHITE)
            for val, w in zip(row, col_widths):
                self.cell(w, 8, tight_text(str(val)), border=0, fill=True, align='C')
            self.ln()
        self.ln(3)

    def highlight_box(self, text):
        self.ln(2)
        self.set_font('K', '', 11)
        self.set_text_color(*CLR_PRIMARY)
        text = tight_text(text)
        x0 = self.get_x()
        y0 = self.get_y()
        self.set_fill_color(*CLR_PRIMARY)
        self.rect(x0, y0, 3, 8, 'F')
        self.set_x(x0 + 7)
        self.multi_cell(self.cw - 7, 7, text, align='L')
        self.ln(2)

    def gap(self, h=4):
        self.ln(h)

    def record_toc(self, title):
        self.toc_entries.append((title, self.page_no()))


